// ============================================================================
// 文件名：lb_method_b_ringbuf.v
// 方  法：方法 B —— 循环缓冲（Ring Buffer）
// 适用层：Conv 层（11×7 卷积核，输入 1×30×10）
//         ※ 与方法 A 参数完全相同，便于对比
// ============================================================================
//
// ★ 与方法 A 的关键区别
//
//   方法 A（寄存器阵列 + 行移位）：
//     push_row 时：110 个 DFF 全部动作（100 次传输 + 10 次新行写入）
//     窗口读取：77 个 4:1 MUX（每个窗口像素一个）
//
//   方法 B（循环缓冲）：
//     push_row 时：仅 10 个 DFF 动作（只写当前槽位） + 1 个计数器更新
//     窗口读取：需要额外的"逻辑行 → 物理槽"地址转换（更多 MUX）
//
//   何时选方法 B：
//     · KH 大（行缓冲行数多），方法 A 的移位开销大时
//     · 关注动态功耗（每次 push_row 翻转的 DFF 更少）
//     · Conv 层 KH=11，方法 B 每次 push_row 节省 100 次 DFF 翻转
//
// ★ 核心思想：不搬数据，只移指针
//
//   把 11 个"槽位（slot）"想象成一个圆盘上的 11 个格子：
//
//                0      1      2  ...  10
//              ┌────┬────┬────┬─────┬────┐
//   slot[i]   │row?│row?│row?│ ... │row?│
//              └────┴────┴────┴─────┴────┘
//                ↑
//              wr_ptr（写指针，指向"下次要被覆盖的最旧槽位"）
//
//   push_row 时：
//     (1) 把新行写入 slot[wr_ptr]（覆盖最旧行，10 次 DFF 写入）
//     (2) wr_ptr = (wr_ptr + 1) % 11（指针前进，1 次 DFF 更新）
//
//   读取窗口时：
//     "逻辑行 r" → "物理槽位 phys = (wr_ptr + r) % 11"
//     slot[phys][col] 即为第 r 个（从旧到新）缓冲行的第 col 列像素
//
// ★ 逐步追踪（以 KH=3 简化示意，原理与 KH=11 相同）：
//
//   初始：wr_ptr=0, slot[0..2]=空
//   push row0: slot[0]=row0, wr_ptr=1
//   push row1: slot[1]=row1, wr_ptr=2
//   push row2: slot[2]=row2, wr_ptr=0（回绕）
//
//   此时缓冲区满（3 行），wr_ptr=0 指向最旧行所在的槽位
//   逻辑行映射（wr_ptr=0）：
//     逻辑行 0（最旧=row0）→ phys=(0+0)%3=0 → slot[0]=row0 ✓
//     逻辑行 1（row1）→ phys=(0+1)%3=1 → slot[1]=row1 ✓
//     逻辑行 2（最新=row2）→ phys=(0+2)%3=2 → slot[2]=row2 ✓
//
//   push row3（下一帧新行）: slot[0]=row3（覆盖 row0）, wr_ptr=1
//   逻辑行映射（wr_ptr=1）：
//     逻辑行 0（最旧=row1）→ phys=(1+0)%3=1 → slot[1]=row1 ✓
//     逻辑行 2（最新=row3）→ phys=(1+2)%3=0 → slot[0]=row3 ✓
//
// ============================================================================

`default_nettype none

module lb_conv_ringbuf #(
    parameter integer KH        = 11,  // 卷积核高度 = 槽位数 = 缓冲行数
    parameter integer ROW_WIDTH = 10,  // 输入特征图宽度（列数）
    parameter integer KW        = 7,   // 卷积核宽度 = 窗口列数
    // 写指针位宽：需要能表示 0..KH-1 = 0..10，需 4 位（2^4=16>11）
    parameter integer PTR_BITS  = 4    // ceil(log2(KH)) = ceil(log2(11)) = 4
)(
    input  wire        clk,
    input  wire        rst_n,

    // ── 行推入接口（与方法 A 完全相同，便于替换）────────────────────────
    // push_row 含义、时序、使用方式与方法 A 相同，详见 lb_method_a_regarray.v
    // 区别在于硬件行为：方法 B 只有 10 个 DFF 动作而非 110 个
    input  wire                    push_row,
    input  wire [ROW_WIDTH*8-1:0]  new_row,   // 10×8=80bit

    // ── 窗口读取接口（与方法 A 接口相同，内部实现不同）─────────────────
    // window 的位宽编排与方法 A 完全一致：
    //   window[(r*KW + c)*8 +: 8] = 逻辑行 r、窗口内列 c 的像素（INT8）
    input  wire [1:0]              col_start,  // 0~3
    output wire [KH*KW*8-1:0]     window      // 77×8=616bit
);

// ============================================================================
// § 1  内部存储（扁平化 1D 数组，避免综合工具处理双动态索引的兼容性问题）
//
//   slot_flat[row * ROW_WIDTH + col] 对应逻辑上的 slot[row][col]
//   slot_flat[0..9]   = 物理槽位 0（10 个列像素）
//   slot_flat[10..19] = 物理槽位 1
//   ...
//   slot_flat[100..109] = 物理槽位 10
//
//   【综合后硬件量（与方法 A 相同）】：
//     KH × ROW_WIDTH = 11 × 10 = 110 个 8bit DFF = 880 个触发器
// ============================================================================
reg signed [7:0] slot_flat [0:KH*ROW_WIDTH-1];  // 110 个 INT8 寄存器（扁平化）
reg [PTR_BITS-1:0] wr_ptr;  // 写指针：下次 push_row 写入的物理槽位编号（0~10）

// ============================================================================
// § 2  时序逻辑：复位 / 写入新行 / 更新写指针
// ============================================================================
// 注意：Verilog-2001 要求循环变量在模块级声明，不能在过程块内部声明
integer c;   // 用于 push_row 时的列遍历循环
integer i;   // 用于复位时的扁平数组遍历循环

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        // ── 异步复位：清零所有 110 个 DFF 和写指针 ──────────────────────
        for (i = 0; i < KH * ROW_WIDTH; i = i + 1)
            slot_flat[i] <= 8'sd0;
        wr_ptr <= {PTR_BITS{1'b0}};

    end else if (push_row) begin
        // ══════════════════════════════════════════════════════════════
        // ── 步骤 1：将新行写入当前写指针指向的槽位 ─────────────────────
        //
        //   slot_flat[wr_ptr * ROW_WIDTH + c] ← new_row[c]
        //
        //   【与方法 A 的关键差异】：
        //   · 方法 A push_row：110 个 DFF 全部更新（大量寄存器翻转）
        //   · 方法 B push_row：仅 10 个 DFF 更新（wr_ptr 指向的 1 个槽位）
        //
        //   【硬件含义】：
        //   wr_ptr 是一个 4bit 计数器，其值决定哪 10 个 DFF 被选中写入。
        //   其余 100 个 DFF 的 CE（时钟使能）保持低电平，完全不翻转。
        //   动态功耗 ≈ 方法 A 的 10/110 ≈ 9%（仅寄存器部分）。
        //
        //   代价：wr_ptr 的计算和传输也需要一些逻辑功耗（很小）。
        // ══════════════════════════════════════════════════════════════
        for (c = 0; c < ROW_WIDTH; c = c + 1)
            // wr_ptr * ROW_WIDTH：4bit 乘以常数 10，综合为移位+加法
            // = (wr_ptr << 3) + (wr_ptr << 1)，不需要乘法器
            slot_flat[wr_ptr * ROW_WIDTH + c] <= new_row[c*8 +: 8];

        // ── 步骤 2：写指针循环递增（模 KH）──────────────────────────────
        //
        //   if (wr_ptr == KH-1): wr_ptr ← 0    （回绕到开头）
        //   else:                wr_ptr ← wr_ptr + 1
        //
        //   【为什么用 if-else 而非 % 运算符？】
        //   % 在 Verilog 综合中生成除法器，面积大、时序差。
        //   简单的比较+条件赋值综合为一个比较器 + 2:1 MUX，效率高。
        if (wr_ptr == KH - 1)
            wr_ptr <= {PTR_BITS{1'b0}};     // 回绕到 0
        else
            wr_ptr <= wr_ptr + 1'b1;        // 正常递增
    end
    // push_row=0：所有 DFF 保持不变（CE 为低），功耗极低
end

// ============================================================================
// § 3  组合逻辑：窗口输出（含"逻辑行 → 物理槽"地址转换）
//
//   【核心步骤】：
//   对每个逻辑行 gr（0=最旧，KH-1=最新）：
//
//   Step A：计算物理槽位
//     ptr_sum  = wr_ptr + gr         （gr 是 generate 常量）
//     phys     = (ptr_sum >= KH) ? (ptr_sum - KH) : ptr_sum
//
//   Step B：计算扁平数组索引
//     flat_idx = phys * ROW_WIDTH + col_start + gc
//                ↑                  ↑             ↑
//           运行时（0~100）     运行时（0~3）  generate常量（0~6）
//
//   Step C：读取像素
//     window[(gr*KW+gc)*8 +: 8] = slot_flat[flat_idx]
//
//   【综合结果（与方法 A 对比）】：
//
//   方法 A 窗口输出逻辑（per 像素）：
//     1 个 4:1 MUX（8bit）→ 选择 4 个相邻列中的一个
//     MUX 开销：77 × 4选1 = 77 个小 MUX
//
//   方法 B 窗口输出逻辑（per 像素）：
//     · Step A：4bit 加法器 + 比较器 + 2:1 MUX → 4bit phys（11 组，按行复用）
//     · Step B：4bit × 常数10 = 7bit 移位加法 + 2bit+常数 加法器 → 7bit flat_idx
//     · Step C：110:1 MUX（8bit）→ 从 110 个位置选一个
//     MUX 开销：77 × 110选1 = 77 个大 MUX，面积约为方法 A 的 27 倍（仅 MUX 部分）
//
//   结论：方法 B 用"窗口读取的额外 MUX 面积"换取"push_row 时更低的功耗"。
// ============================================================================
genvar gr, gc;
generate
    for (gr = 0; gr < KH; gr = gr + 1) begin : G_ROW
        // ── Step A：计算逻辑行 gr 对应的物理槽位 phys ────────────────
        //
        //   ptr_sum = wr_ptr + gr（gr 是常量，wr_ptr 是运行时 4bit 信号）
        //   需要 5bit 容纳求和结果（最大 10+10=20）
        //
        //   phys = ptr_sum % KH，用减法实现（避免除法器）：
        //     · ptr_sum 范围 [gr, gr+10]
        //     · 若 ptr_sum ≥ KH(=11)：phys = ptr_sum - 11（结果 0..9）
        //     · 若 ptr_sum < KH     ：phys = ptr_sum（结果 0..10）
        //   两种情况结果都在 [0, 10]，4bit 足够表示。
        //
        wire [4:0] ptr_sum;   // 5bit，容纳 wr_ptr(0..10) + gr(0..10)，最大 20
        wire [4:0] ptr_diff;  // ptr_sum - KH，用于取模减法
        wire [PTR_BITS-1:0] phys;  // 物理槽位索引（0..10，4bit 足够）

        // gr 在 generate 展开后为常量（0, 1, ..., 10）
        // "wr_ptr + gr" 综合为"4bit 信号加常数"，得到 5bit 结果
        // 注意：Verilog 整数（integer）运算为 32bit，赋值给 ptr_sum[4:0] 时截断，
        //       因最大值 20 < 32，截断不丢失信息。
        assign ptr_sum  = wr_ptr + gr;            // wr_ptr(4bit) + gr(常量) → 5bit
        assign ptr_diff = ptr_sum - KH;           // KH=11，当 ptr_sum>=11 时有效
        // 减法实现取模：综合为 1 个 5bit 减法器 + 1 个比较器 + 1 个 4bit 2:1 MUX
        assign phys = (ptr_sum >= KH) ? ptr_diff[PTR_BITS-1:0] : ptr_sum[PTR_BITS-1:0];

        for (gc = 0; gc < KW; gc = gc + 1) begin : G_COL
            // ── Step B + C：计算扁平索引并读取像素 ────────────────────
            //
            //   flat_idx = phys * ROW_WIDTH + col_start + gc
            //
            //   phys * ROW_WIDTH = phys * 10：
            //     综合为：(phys << 3) + (phys << 1)（两个移位 + 1个加法器）
            //     结果范围 [0, 100]，需 7bit
            //
            //   + col_start（2bit，运行时）+ gc（generate 常量，0..6）：
            //     总范围 [gc, 100+3+gc] ⊆ [0, 109]，7bit 足够（2^7=128>109）✓
            //     不越界：KH * ROW_WIDTH - 1 = 110 - 1 = 109 ✓
            //
            //   slot_flat[7bit 动态索引]：综合为 110:1 MUX（8bit 宽）
            //   同一 gr 的 7 个 gc 共享相同的 phys（phys 被 G_ROW 级复用）
            wire [6:0] flat_idx;
            // gc 是 generate 常量，在综合展开后变成整数字面量（如 3）
            // 整数字面量参与运算时为 32bit，赋值给 flat_idx[6:0] 时截断，不丢失信息
            assign flat_idx = phys * ROW_WIDTH + col_start + gc;
            //                 ↑运行时  ↑参数常数    ↑运行时  ↑generate常数

            assign window[(gr * KW + gc) * 8 +: 8] = slot_flat[flat_idx];
            //                ↑常量打包位置                    ↑
            //                                       110:1 MUX（8bit 宽）
        end
    end
endgenerate

endmodule

`default_nettype wire
// ============================================================================
// 方法 A vs 方法 B 综合对比（本项目 Conv 层参数：KH=11, ROW_WIDTH=10, KW=7）
//
// ┌──────────────┬──────────────────────────┬──────────────────────────┐
// │  对比维度     │    方法 A（寄存器阵列）   │    方法 B（循环缓冲）   │
// ├──────────────┼──────────────────────────┼──────────────────────────┤
// │ 内部存储      │ 110 个 8bit DFF           │ 110 个 8bit DFF + 1个   │
// │              │ （buf[0..10][0..9]）       │  4bit 写指针            │
// ├──────────────┼──────────────────────────┼──────────────────────────┤
// │ push_row 时  │ 110 个 DFF 全部动作        │ 10+1=11 个 DFF 动作      │
// │ DFF 翻转次数  │ （移位100 + 写入10）       │ （写入10 + 指针更新1）  │
// ├──────────────┼──────────────────────────┼──────────────────────────┤
// │ 窗口读取 MUX │ 77 个 4:1 MUX（8bit）     │ 77 个 110:1 MUX（8bit） │
// │ （额外组合面积）│ （每行直接索引，仅列选择）│ （行+列均需动态选择）  │
// ├──────────────┼──────────────────────────┼──────────────────────────┤
// │ 设计复杂度   │ 简单，直观                 │ 较复杂（指针/取模逻辑） │
// ├──────────────┼──────────────────────────┼──────────────────────────┤
// │ 适用情况      │ KH 较小（如 DWConv KH=3） │ KH 较大（Conv KH=11），  │
// │              │ 或对面积有严格要求         │ 关注动态功耗            │
// └──────────────┴──────────────────────────┴──────────────────────────┘
//
// ★ 本项目建议：
//   对于 Conv 层（KH=11）：方法 B 节省约 91% 的 push_row 寄存器翻转，
//     代价是窗口 MUX 面积增大，综合面积可能增加约 15~30%。
//   对于 DWConv 层（KH=3）：差别不大，方法 A 更简单，推荐使用方法 A。
//
// ★ 使用说明（与方法 A 接口完全兼容，可直接替换）：
//
//   lb_conv_ringbuf #(
//       .KH       (11),
//       .ROW_WIDTH(10),
//       .KW       (7),
//       .PTR_BITS (4)
//   ) u_lb_conv (
//       .clk      (clk),
//       .rst_n    (rst_n),
//       .push_row (lb_push_row),
//       .new_row  (lb_new_row),
//       .col_start(lb_col_start),
//       .window   (lb_window)     // 616bit，接 MAC 阵列
//   );
// ============================================================================
