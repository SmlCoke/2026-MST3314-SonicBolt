// 外部控制信号时序示意（Conv 层初始填充阶段）：
//
//   clk:      _↑__↑__↑__↑__↑__↑__↑__↑__↑__↑__↑__↑__↑_
//   push_row: ‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾‾
//             ← 推入 row0 →← row1 →← ... →← row10 →
//                      （每次 push_row=1 持续 1 拍）
//
//   之后进入卷积阶段：
//   col_start: 0 → 1 → 2 → 3 → (push row11) → 0 → 1 → 2 → 3 → ...
//   push_row:  0   0   0   0      1            0   0   0   0   ...
// ============================================================================
