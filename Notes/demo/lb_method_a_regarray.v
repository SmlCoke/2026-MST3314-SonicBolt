// ============================================================================
// 文件名：lb_method_a_regarray.v
// 方  法：方法 A —— 寄存器阵列 + 行移位（Register Array with Row Shift）
// 适用层：Conv 层（11×7 卷积核，输入 1×30×10）
// ============================================================================
//
// ★ 对应 Python 类（PyRTL-CNN/rtl_primitives.py）：
//
//   class LineBuffer:
//       def __init__(self, num_rows, row_width, ...):
//           self._buf = [[0]*row_width for _ in range(num_rows)]
//
//       def load_rows(self, rows_2d):          # ← 对应 push_row × KH 次
//           for r in range(self.num_rows):
//               for c in range(self.row_width):
//                   self._buf[r][c] = clamp_int8(rows_2d[r][c])
//
//       def get_window(self, col_start, kernel_w):  # ← 对应 window 端口
//           return [[self._buf[r][col_start+c]
//                    for c in range(kernel_w)]
//                   for r in range(self.num_rows)]
//
// ★ 硬件直觉：
//
//   把 11 行 × 10 列想象成一张"纸条"钉在墙上的 110 个格子，
//   每个格子存放一个 INT8 像素（8 个 D 触发器）。
//
//   ┌──────────────────────────────────────────┐
//   │ buf[0][0..9]   ← 最旧的一行（即将被淘汰）│
//   │ buf[1][0..9]                             │
//   │ buf[2][0..9]                             │  ← 行缓冲区（共 110 个寄存器）
//   │    ...                                   │
//   │ buf[9][0..9]                             │
//   │ buf[10][0..9]  ← 最新的一行（刚读入）   │
//   └──────────────────────────────────────────┘
//         ↑ col_start 决定读哪几列
//
//   每次 push_row（新行到来时）：
//     → buf[0] 被丢弃（最旧行"掉出"）
//     → buf[1..10] 整体上移一行：buf[r] ← buf[r+1]
//     → 新行写入 buf[10]（最末行）
//
//   任意时刻，用 col_start 从缓冲区里"切"出一个 11×7 的窗口，
//   组合逻辑立即输出，供 MAC 阵列并行使用。
//
// ★ 注意事项：
//   · push_row 每次触发 100 次寄存器传输（KH-1=10 行 × ROW_WIDTH=10 列）
//     + 10 次新行写入，合计 110 次 DFF 采样（每个 DFF 都动作）。
//   · 若希望减少翻转功耗，改用方法 B（环形缓冲，每次仅写 10 个 DFF）。
// ============================================================================

`default_nettype none

module lb_conv_regarray #(
    // ── 参数（本项目 Conv 层固定值）──────────────────────────────────────
    parameter integer KH        = 11,  // 卷积核高度 = 行缓冲行数
                                       // Conv 层：11 行
    parameter integer ROW_WIDTH = 10,  // 输入特征图宽度（列数）
                                       // Conv 输入：每行 10 列
    parameter integer KW        = 7    // 卷积核宽度 = 窗口列数
                                       // Conv 层：7 列
    // 推导参数（在外部使用）：
    //   OUT_COLS = ROW_WIDTH - KW + 1 = 10 - 7 + 1 = 4
    //   col_start 取值范围：0, 1, 2, 3
)(
    input  wire        clk,
    input  wire        rst_n,   // 低电平异步复位

    // ── 行推入接口 ────────────────────────────────────────────────────────
    //
    // 【什么时候拉高 push_row？】
    //   外部控制器（FSM）从 Input SRAM 读完一整行（10 个像素）后，
    //   将这 10 个像素拼成 new_row 总线，同时拉高 push_row 一拍。
    //   行缓冲在下一个时钟上升沿完成移位和写入。
    //
    // 【push_row 在整个 Conv 层推理中触发多少次？】
    //   初始填充：11 次（等待足够多行后才能开始卷积）
    //   逐行滑动：19 次（处理输出行 1~19，每次推入一行新数据）
    //   共计：30 次（= 输入高度 30 行）
    //
    // new_row 的位宽编排（低列索引在低位）：
    //   new_row[0*8 +: 8] = 列 0 的像素（最左列，INT8）
    //   new_row[1*8 +: 8] = 列 1 的像素
    //   ...
    //   new_row[9*8 +: 8] = 列 9 的像素（最右列，INT8）
    // 每次读入一行，共 80 个 pixel
    input  wire                    push_row,
    input  wire [ROW_WIDTH*8-1:0]  new_row,   // 10 像素 × 8bit = 80bit

    // ── 窗口读取接口（纯组合逻辑，无需等待时钟）──────────────────────────
    //
    // col_start：窗口左边界列索引
    //   · Conv 输出列数 = 10 - 7 + 1 = 4，故 col_start ∈ {0, 1, 2, 3}
    //   · 由外部列计数器驱动：计算完一列输出后递增，到 3 后回到 0 并 push_row
    //
    // window：11×7=77 个 INT8 像素的并行输出（行优先打包）
    //   · window[(r*KW + c)*8 +: 8] = buf[r][col_start + c]
    //     其中 r ∈ [0, KH-1]，c ∈ [0, KW-1]
    //   · 举例（col_start=2）：
    //       window[0*7+0 ... 0*7+7]  = buf[0][2]  buf[0][3] ... buf[0][8]
    //       window[1*7+0 ... 1*7+7]  = buf[1][2]  ...
    //       window[10*7+0...]        = buf[10][2] buf[10][3] ... buf[10][8]
    input  wire [1:0]              col_start,  // 0~3，2bit
    output wire [KH*KW*8-1:0]     window      // 77×8=616bit
);

// ============================================================================
// § 1  内部寄存器阵列
//
//   buf[r][c]：行 r、列 c 的 INT8 像素
//   · 行下标 r：0 = 最旧行，KH-1(=10) = 最新行
//   · 列下标 c：0 = 最左列，ROW_WIDTH-1(=9) = 最右列
//
//   【综合后硬件量】：
//     KH × ROW_WIDTH = 11 × 10 = 110 个 8bit DFF
//     = 880 个触发器 + 少量 MUX（用于 push_row 时的数据选择）
// ============================================================================
reg signed [7:0] buf [0:KH-1][0:ROW_WIDTH-1];

// ============================================================================
// § 2  时序逻辑：复位 / 行移位 / 新行写入
// ============================================================================
integer r, c;   // always 块内的循环变量（综合时展开为并行逻辑，无实际硬件开销）

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        // ── 异步复位：清零所有 110 个寄存器 ─────────────────────────────
        // 综合后：rst_n 连接到所有 DFF 的异步复位端（CLR/RST）
        for (r = 0; r < KH; r = r + 1)
            for (c = 0; c < ROW_WIDTH; c = c + 1)
                buf[r][c] <= 8'sd0;
    
    end else if (push_row) begin
        // ══════════════════════════════════════════════════════════════
        // ── 步骤 1：行移位（最旧行丢弃，其余行向上移动一行）─────────
        //
        //   for r = 0 to KH-2：
        //     buf[r][c] ← buf[r+1][c]    （下一行的值复制到当前行）
        //
        //   【硬件含义】：这不是"搬运数据"，而是寄存器的连线方式：
        //     buf[0][c] 的 D 端 ←────────────── buf[1][c] 的 Q 端
        //     buf[1][c] 的 D 端 ←────────────── buf[2][c] 的 Q 端
        //     buf[2][c] 的 D 端 ←────────────── buf[3][c] 的 Q 端
        //     ...
        //     buf[9][c] 的 D 端 ←────────────── buf[10][c] 的 Q 端
        //
        //   每个时钟上升沿，所有 DFF 同时采样 D 端，
        //   整个"移位"在一个时钟周期内原子完成。
        //
        //   代价：(KH-1) × ROW_WIDTH = 10 × 10 = 100 个 DFF 的值变化
        //   （这就是方法 A 相比方法 B 动态功耗更高的原因）
        // ══════════════════════════════════════════════════════════════
        for (r = 0; r < KH-1; r = r + 1)       // r = 0, 1, 2, ..., 9
            for (c = 0; c < ROW_WIDTH; c = c + 1)
                buf[r][c] <= buf[r+1][c];       // 向"上"（低索引方向）移位

        // ── 步骤 2：将新行写入 buf[KH-1]（最末行，索引 10）──────────
        //
        //   new_row[c*8 +: 8]：从打包总线中提取第 c 列的 8bit 像素
        //   语法解析：从位 c*8 开始，取 8 位 → 即 new_row[(c+1)*8-1 : c*8]
        //
        //   这 10 个赋值是并行的（同一个时钟沿完成），
        //   对应于 10 个 DFF 从 new_row 总线采样。
        for (c = 0; c < ROW_WIDTH; c = c + 1)
            buf[KH-1][c] <= new_row[c*8 +: 8];

        // ── 总结：push_row 触发后，当前时钟上升沿同时完成：
        //   · 100 次寄存器间传输（移位）
        //   · 10  次外部数据写入（新行）
        //   · 合计 110 个 DFF 状态更新
    end
    // push_row=0 时：所有 DFF 保持当前值（寄存器使能 CE 为低）
    // 允许在同一组行数据上连续多拍读取不同的 col_start 窗口
end

// ============================================================================
// § 3  组合逻辑：窗口输出
//
//   【核心思想】：
//   窗口是从行缓冲中"切"出来的，col_start 决定切的起始位置。
//   这是纯组合逻辑（assign），没有时钟，没有延迟。
//
//   对每个 (r, c) 输出位置：
//     window[(r*KW + c)*8 +: 8] = buf[r][col_start + c]
//
//   ┌──────────────────────────────────────────────┐
//   │ col_start=0: 窗口列 = [0,1,2,3,4,5,6]       │
//   │ col_start=1: 窗口列 = [1,2,3,4,5,6,7]       │
//   │ col_start=2: 窗口列 = [2,3,4,5,6,7,8]       │
//   │ col_start=3: 窗口列 = [3,4,5,6,7,8,9]       │
//   └──────────────────────────────────────────────┘
//
//   【综合结果（重要！）】：
//   generate 展开后得到 77 条独立的 assign 语句，每条的结构是：
//
//     assign window[(r*7+c)*8 +: 8] = buf[r][col_start + CONST_c];
//                                               ↑             ↑
//                                      运行时 2bit 信号   generate 常量
//
//   "col_start + CONST_c" 是一个动态数组索引，综合工具实现为：
//
//     4:1 MUX（8bit 宽），由 col_start 选择：
//       sel=0 → buf[r][CONST_c + 0]
//       sel=1 → buf[r][CONST_c + 1]
//       sel=2 → buf[r][CONST_c + 2]
//       sel=3 → buf[r][CONST_c + 3]
//
//   共产生 KH × KW = 11 × 7 = 77 个 4:1 MUX（每个 8bit 宽）。
//   所有 MUX 并行工作，在 col_start 变化后的一个组合逻辑延迟内输出。
//
//   【越界检查】：
//   col_start ∈ {0,1,2,3}，gc ∈ {0,..,6}
//   最大索引 = col_start_max + gc_max = 3 + 6 = 9 = ROW_WIDTH-1 ✓
//   不会越界。
// ============================================================================
genvar gr, gc;
generate
    for (gr = 0; gr < KH; gr = gr + 1) begin : G_ROW
        // gr 是 generate 循环变量，在综合展开时变为常量 0, 1, 2, ..., 10
        for (gc = 0; gc < KW; gc = gc + 1) begin : G_COL
            // gc 是 generate 循环变量，综合展开时变为常量 0, 1, 2, ..., 6

            // 本语句综合展开后变为 77 条独立的 assign（每条针对一个像素输出）：
            //   gr=0,gc=0: assign window[ 0*8 +: 8] = buf[0][col_start+0];
            //   gr=0,gc=1: assign window[ 8   +: 8] = buf[0][col_start+1];
            //   ...
            //   gr=10,gc=6: assign window[615 +: 8] = buf[10][col_start+6];
            assign window[(gr * KW + gc) * 8 +: 8] = buf[gr][col_start + gc];
            //                        ↑                  ↑          ↑
            //               打包索引（常量）       行（常量）  列（含运行时 col_start）
        end
    end
endgenerate

endmodule

`default_nettype wire
