// 功能描述:
//   MAC 树流水线第 3 级 — 最终求和 + 偏置加法
//   将 10 个 INT20 部分和相加得到总和，再加上 INT32 偏置，
//   输出 1 个 INT32 MAC 结果。
//
// 流水线延迟: 1 个时钟周期
// ---------------------------------------------------------------------------
// 端口说明:
//   clk        — 系统时钟
//   rst_n      — 异步低电平复位
//   valid_in   — 输入数据有效标志
//   psum_flat  — 10 × INT20 部分和，展平为 200-bit
//   bias_in    — INT16 偏置
//   valid_out  — 输出数据有效标志（延迟 1 拍）
//   mac_out    — INT32 最终乘累加结果
// ===========================================================================

module MAC77_AddTree_s2 (
    input  wire                clk,
    input  wire                rst_n,
    input  wire                valid_in,
    input  wire [200-1:0]      psum_flat,   // 10 × INT20
    input  wire signed [15:0]  bias_in,     // INT16 偏置
    output reg                 valid_out,
    output reg  signed [31:0]  mac_out      // INT32 结果
);

    // ------------------------------------------------------------------
    // valid 信号延迟 1 拍
    // ------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            valid_out <= 1'b0;
        else
            valid_out <= valid_in;
    end

    // ------------------------------------------------------------------
    // 解包 10 个 INT20 部分和
    // ------------------------------------------------------------------
    wire signed [19:0] ps [0:9];
    genvar i;
    generate
        for (i = 0; i < 10; i = i + 1) begin : gen_unpack
            assign ps[i] = psum_flat[i*20 +: 20];
        end
    endgenerate

    // ------------------------------------------------------------------
    // 三级加法树：10 → 5 → 3 → 2 → 1，再加偏置
    // ------------------------------------------------------------------
    // 第一级：10 → 5
    wire signed [20:0] l1_0 = {ps[0][19], ps[0]} + {ps[1][19], ps[1]};
    wire signed [20:0] l1_1 = {ps[2][19], ps[2]} + {ps[3][19], ps[3]};
    wire signed [20:0] l1_2 = {ps[4][19], ps[4]} + {ps[5][19], ps[5]};
    wire signed [20:0] l1_3 = {ps[6][19], ps[6]} + {ps[7][19], ps[7]};
    wire signed [20:0] l1_4 = {ps[8][19], ps[8]} + {ps[9][19], ps[9]};

    // 第二级：5 → 3
    wire signed [21:0] l2_0 = {l1_0[20], l1_0} + {l1_1[20], l1_1};
    wire signed [21:0] l2_1 = {l1_2[20], l1_2} + {l1_3[20], l1_3};
    wire signed [21:0] l2_2 = {{1{l1_4[20]}}, l1_4};

    // 第三级：3 → 2
    wire signed [22:0] l3_0 = {l2_0[21], l2_0} + {l2_1[21], l2_1};
    wire signed [22:0] l3_1 = {{1{l2_2[21]}}, l2_2};

    // 最终求和
    wire signed [23:0] total_sum = {l3_0[22], l3_0} + {l3_1[22], l3_1};

    // 加偏置（扩展到 INT32）
    wire signed [31:0] result = {{8{total_sum[23]}}, total_sum} + {{16{bias_in[15]}}, bias_in};

    // ------------------------------------------------------------------
    // 输出寄存器打拍
    // ------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            mac_out <= 32'sd0;
        else if (valid_in)
            mac_out <= result;
    end

endmodule
