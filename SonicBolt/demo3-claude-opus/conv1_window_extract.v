// 功能描述:
//   从行缓冲器的 11 行数据中，根据列计数器 col_cnt 提取 11×7 的卷积窗口。
//   纯组合逻辑，零时钟延迟。
//
// 提取规则:
//   窗口 win[r][c] = row_data[r][(col_cnt + c) * 8 +: 8]
//   其中 r = 0..10, c = 0..6, col_cnt = 0..3
//   输出按行主序展平：win_flat[(r*7+c)*8 +: 8]
//
// 输入行格式:
//   每行 80-bit = 10 个 INT8，pixel[0] 在低 8 位
//   行缓冲输出: row_data[i*80 +: 80] 对应逻辑第 i 行
// ---------------------------------------------------------------------------
// 端口说明:
//   row_data  — 11 × 80-bit 行数据（展平为 880-bit）
//   col_cnt   — 列偏移计数器（0~3，对应 4 个水平滑动位置）
//   win_flat  — 11 × 7 = 77 个 INT8，展平为 616-bit
// ===========================================================================

module conv1_window_extract (
    input  wire [880-1:0]     row_data,   // 11 × 80-bit
    input  wire [1:0]         col_cnt,    // 0 ~ 3
    output wire [616-1:0]     win_flat    // 77 × INT8
);

    // ------------------------------------------------------------------
    // 组合逻辑：从 11 行 × 10 列中提取 11 行 × 7 列的子窗口
    // ------------------------------------------------------------------
    genvar r, c;
    generate
        for (r = 0; r < 11; r = r + 1) begin : gen_row
            for (c = 0; c < 7; c = c + 1) begin : gen_col
                // 源列索引 = col_cnt + c（范围 0~9，不会越界）
                // 在展平数组中的位偏移
                wire [3:0] src_col = {2'b0, col_cnt} + c[3:0];
                assign win_flat[(r*7+c)*8 +: 8] = row_data[r*80 + src_col*8 +: 8];
            end
        end
    endgenerate

endmodule
